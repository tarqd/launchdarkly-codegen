import { describe, expect, it } from 'vitest';
import type { Flag, FlagModel } from '@launchtarqly/core';
import { javaEmitter } from '../src/index.js';
import { modelFlag } from '../../core/test/builders.js';

const cfg = { id: 'java', out: 'src/main/java/com/example/flags', package: 'com.example.flags', sdkMajor: 7 } as const;
const ctx = { generatorVersion: '0.3.0' };

function emit(...flags: Flag[]): string {
  const model: FlagModel = { projectKey: 'my-project', flags };
  return javaEmitter.emit(model, cfg, ctx)[0]!.contents;
}

describe('java emitter', () => {
  it('writes one Flags.java into the out directory', () => {
    const files = javaEmitter.emit({ projectKey: 'my-project', flags: [modelFlag('checkout-v2')] }, cfg, ctx);
    expect(files.map((f) => f.path)).toEqual(['src/main/java/com/example/flags/Flags.java']);
  });

  it('emits the Flags class, its methods and Keys for a boolean flag', () => {
    expect(emit(modelFlag('checkout-v2', { name: 'Checkout V2' }))).toBe(`// Code generated by launchdarkly-codegen. DO NOT EDIT.
// project: my-project   generator: 0.3.0
package com.example.flags;

import com.launchdarkly.sdk.EvaluationDetail;
import com.launchdarkly.sdk.LDContext;
import com.launchdarkly.sdk.server.interfaces.LDClientInterface;

/** Typed accessors for the flags in LaunchDarkly project {@code my-project}. */
public final class Flags {
  /** The wrapped SDK client. */
  private final LDClientInterface client;

  /**
   * Wraps an SDK client.
   *
   * @param client the LaunchDarkly client to evaluate flags with
   */
  public Flags(LDClientInterface client) {
    this.client = client;
  }

  /**
   * Checkout V2
   *
   * @param context the context to evaluate the flag for
   * @param fallback the value to return if the flag can't be evaluated
   * @return the flag's value for {@code context}
   */
  public boolean checkoutV2(LDContext context, boolean fallback) {
    return client.boolVariation(Keys.CHECKOUT_V2, context, fallback);
  }

  /**
   * Checkout V2
   *
   * @param context the context to evaluate the flag for
   * @param fallback the value to return if the flag can't be evaluated
   * @return the flag's value for {@code context}, with the reason it was chosen
   */
  public EvaluationDetail<Boolean> checkoutV2Detail(LDContext context, boolean fallback) {
    return client.boolVariationDetail(Keys.CHECKOUT_V2, context, fallback);
  }

  /** The raw key of every flag, for code that needs the key itself. */
  public static final class Keys {
    /** Not instantiable. */
    private Keys() {}

    /** {@code checkout-v2} */
    public static final String CHECKOUT_V2 = "checkout-v2";
  }
}
`);
  });

  it('maps string, number and json flags to the typed SDK methods', () => {
    const out = emit(
      { ...modelFlag('pricing-tier'), kind: 'string' },
      { ...modelFlag('discount-rate'), kind: 'number', numberType: 'double' },
      { ...modelFlag('max-items'), kind: 'number', numberType: 'int' },
      { ...modelFlag('checkout-config'), kind: 'json' },
    );
    for (const expected of [
      '  public String pricingTier(LDContext context, String fallback) {\n    return client.stringVariation(Keys.PRICING_TIER, context, fallback);\n',
      '  public EvaluationDetail<String> pricingTierDetail(LDContext context, String fallback) {\n    return client.stringVariationDetail(Keys.PRICING_TIER, context, fallback);\n',
      '  public double discountRate(LDContext context, double fallback) {\n    return client.doubleVariation(Keys.DISCOUNT_RATE, context, fallback);\n',
      '  public EvaluationDetail<Double> discountRateDetail(LDContext context, double fallback) {\n    return client.doubleVariationDetail(Keys.DISCOUNT_RATE, context, fallback);\n',
      '  public int maxItems(LDContext context, int fallback) {\n    return client.intVariation(Keys.MAX_ITEMS, context, fallback);\n',
      '  public EvaluationDetail<Integer> maxItemsDetail(LDContext context, int fallback) {\n    return client.intVariationDetail(Keys.MAX_ITEMS, context, fallback);\n',
      '  public LDValue checkoutConfig(LDContext context, LDValue fallback) {\n    return client.jsonValueVariation(Keys.CHECKOUT_CONFIG, context, fallback);\n',
      '  public EvaluationDetail<LDValue> checkoutConfigDetail(LDContext context, LDValue fallback) {\n    return client.jsonValueVariationDetail(Keys.CHECKOUT_CONFIG, context, fallback);\n',
      '    public static final String MAX_ITEMS = "max-items";\n',
    ]) {
      expect(out).toContain(expected);
    }
  });

  it('defaults a number flag without a numberType to double', () => {
    expect(emit({ ...modelFlag('rate'), kind: 'number' })).toContain('  public double rate(LDContext context, double fallback) {');
  });

  it('imports LDValue only when a json flag exists', () => {
    const imports = (out: string) => out.split('\n').filter((l) => l.startsWith('import '));
    expect(imports(emit({ ...modelFlag('config'), kind: 'json' }))).toEqual([
      'import com.launchdarkly.sdk.EvaluationDetail;',
      'import com.launchdarkly.sdk.LDContext;',
      'import com.launchdarkly.sdk.LDValue;',
      'import com.launchdarkly.sdk.server.interfaces.LDClientInterface;',
    ]);
    expect(imports(emit(modelFlag('on')))).not.toContain('import com.launchdarkly.sdk.LDValue;');
  });

  it('imports only the client interface when there are no flags', () => {
    const out = emit();
    expect(out.split('\n').filter((l) => l.startsWith('import '))).toEqual([
      'import com.launchdarkly.sdk.server.interfaces.LDClientInterface;',
    ]);
    expect(out).toContain(`  /** The raw key of every flag, for code that needs the key itself. */
  public static final class Keys {
    /** Not instantiable. */
    private Keys() {}
  }
}
`);
  });

  it('names the methods and the constant from the java alias', () => {
    const out = emit(modelFlag('2fa-enabled', { aliases: { java: 'twoFactorEnabled', 'ts-server': 'tsName' } }));
    expect(out).toContain('  public boolean twoFactorEnabled(LDContext context, boolean fallback) {');
    expect(out).toContain('  public EvaluationDetail<Boolean> twoFactorEnabledDetail(LDContext context, boolean fallback) {');
    expect(out).toContain('    return client.boolVariation(Keys.TWO_FACTOR_ENABLED, context, fallback);');
    expect(out).toContain('    public static final String TWO_FACTOR_ENABLED = "2fa-enabled";');
    expect(out).not.toContain('tsName');
  });

  it('writes each flag in model order, a blank line before every member', () => {
    const out = emit(modelFlag('a-flag'), modelFlag('b-flag'));
    expect(out.indexOf('aFlag(')).toBeLessThan(out.indexOf('bFlag('));
    expect(out).toContain(`    return client.boolVariationDetail(Keys.A_FLAG, context, fallback);
  }

  /**`);
    expect(out).toContain(`    public static final String A_FLAG = "a-flag";

    /** {@code b-flag} */
    public static final String B_FLAG = "b-flag";
  }
`);
  });

  it('rejects a missing package', () => {
    const { package: _omitted, ...noPackage } = cfg;
    expect(() => javaEmitter.emit({ projectKey: 'p', flags: [] }, noPackage, ctx)).toThrow(/java target: `package` is required/);
  });
});
