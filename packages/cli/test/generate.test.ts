import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { projectDir, runCli, SNAPSHOTS_DIR } from './helpers.js';

const snapshot = join(SNAPSHOTS_DIR, 'boolean-flags.json');
const minimalConfig = {
  project: 'my-project',
  targets: [{ id: 'ts-server', out: 'src/flags.generated.ts', sdkMajor: 9 }],
};

describe('generate --from-snapshot', () => {
  it('writes the ts-server file to the configured out, relative to the config file', async () => {
    const dir = await projectDir(minimalConfig);
    const result = await runCli(['generate', '--from-snapshot', snapshot], dir);
    expect(result).toMatchObject({ exitCode: 0, stderr: '' });
    const out = await readFile(join(dir, 'src/flags.generated.ts'), 'utf8');
    expect(out).toMatch(/^\/\/ Code generated by launchdarkly-codegen\. DO NOT EDIT\.\n/);
  });

  it('produces identical bytes across runs', async () => {
    const dir = await projectDir(minimalConfig);
    await runCli(['generate', '--from-snapshot', snapshot], dir);
    const first = await readFile(join(dir, 'src/flags.generated.ts'), 'utf8');
    await runCli(['generate', '--from-snapshot', snapshot], dir);
    const second = await readFile(join(dir, 'src/flags.generated.ts'), 'utf8');
    expect(second).toBe(first);
  });

  it('reads the config named by --config', async () => {
    const dir = await projectDir({ ...minimalConfig, targets: [{ ...minimalConfig.targets[0], out: 'a.ts' }] });
    const elsewhere = await projectDir({});
    const result = await runCli(
      ['generate', '--config', join(dir, 'launchdarkly-codegen.config.json'), '--from-snapshot', snapshot],
      elsewhere,
    );
    expect(result.exitCode).toBe(0);
    await expect(readFile(join(dir, 'a.ts'), 'utf8')).resolves.toContain('export class Flags');
  });

  it('exits 2 with a message when there is no config file', async () => {
    const dir = await projectDir({});
    const result = await runCli(['generate', '--from-snapshot', snapshot, '--config', join(dir, 'nope.json')], dir);
    expect(result.exitCode).toBe(2);
    expect(result.stderr).toContain('nope.json');
  });

  it('exits 2 when a target is not supported', async () => {
    const dir = await projectDir({ project: 'my-project', targets: [{ id: 'cobol', out: 'x', sdkMajor: 1 }] });
    const result = await runCli(['generate', '--from-snapshot', snapshot], dir);
    expect(result.exitCode).toBe(2);
    expect(result.stderr).toContain('cobol');
  });

  it('exits 2 on an unknown command', async () => {
    const result = await runCli(['frobnicate'], await projectDir(minimalConfig));
    expect(result.exitCode).toBe(2);
  });
});
