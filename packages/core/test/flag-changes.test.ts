import { readdirSync, readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import { parseTsServerFlags, summarizeFlagChanges } from '../src/index.js';

const GOLDEN = resolve(import.meta.dirname, '../../../fixtures/golden/ts-server');

/** ts-server output in the shape the emitter produces, including later additions (docs, more kinds). */
const OLD = `// Code generated by launchdarkly-codegen. DO NOT EDIT.
// project: my-project   generator: 0.1.0

import type { LDClient, LDContext, LDEvaluationDetailTyped } from '@launchdarkly/node-server-sdk';

export class Flags {
  constructor(private readonly client: LDClient) {}

  /**
   * Checkout V2
   *
   * key: \`checkout-v2\` · tags: checkout, q3 · maintainer: ada@example.com
   * https://app.launchdarkly.com/projects/my-project/flags/checkout-v2
   */
  checkoutV2(context: LDContext, fallback: boolean): Promise<boolean> {
    return this.client.boolVariation('checkout-v2', context, fallback);
  }
  /** Checkout V2 (detail). */
  checkoutV2Detail(context: LDContext, fallback: boolean): Promise<LDEvaluationDetailTyped<boolean>> {
    return this.client.boolVariationDetail('checkout-v2', context, fallback);
  }

  /**
   * Pricing tier
   * @deprecated Use \`pricingTierV2\` instead.
   */
  pricingTier(context: LDContext, fallback: string): Promise<string> {
    return this.client.stringVariation('pricing-tier', context, fallback);
  }
  pricingTierDetail(context: LDContext, fallback: string): Promise<LDEvaluationDetailTyped<string>> {
    return this.client.stringVariationDetail('pricing-tier', context, fallback);
  }

  maxItems(context: LDContext, fallback: number): Promise<number> {
    return this.client.numberVariation('max-items', context, fallback);
  }
  maxItemsDetail(context: LDContext, fallback: number): Promise<LDEvaluationDetailTyped<number>> {
    return this.client.numberVariationDetail('max-items', context, fallback);
  }

  checkoutConfig(context: LDContext, fallback: unknown): Promise<unknown> {
    return this.client.jsonVariation('checkout-config', context, fallback);
  }
  checkoutConfigDetail(context: LDContext, fallback: unknown): Promise<LDEvaluationDetailTyped<unknown>> {
    return this.client.jsonVariationDetail('checkout-config', context, fallback);
  }

  oldThing(context: LDContext, fallback: boolean): Promise<boolean> {
    return this.client.boolVariation('old-thing', context, fallback);
  }
  oldThingDetail(context: LDContext, fallback: boolean): Promise<LDEvaluationDetailTyped<boolean>> {
    return this.client.boolVariationDetail('old-thing', context, fallback);
  }
}

export const FlagKeys = {
  /** Checkout V2 */
  checkoutV2: 'checkout-v2',
  /** @deprecated Use \`pricingTierV2\` instead. */
  pricingTier: 'pricing-tier',
  maxItems: 'max-items',
  checkoutConfig: 'checkout-config',
  oldThing: 'old-thing',
} as const;
`;

describe('parseTsServerFlags', () => {
  it('reads key, identifier and kind for every FlagKeys entry', () => {
    expect(parseTsServerFlags(OLD)).toEqual([
      { key: 'checkout-v2', identifier: 'checkoutV2', kind: 'boolean' },
      { key: 'pricing-tier', identifier: 'pricingTier', kind: 'string' },
      { key: 'max-items', identifier: 'maxItems', kind: 'number' },
      { key: 'checkout-config', identifier: 'checkoutConfig', kind: 'json' },
      { key: 'old-thing', identifier: 'oldThing', kind: 'boolean' },
    ]);
  });

  it.each(readdirSync(GOLDEN).filter((f) => f.endsWith('.ts')))('parses the %s golden file', (name) => {
    const text = readFileSync(join(GOLDEN, name), 'utf8');
    const keys = /export const FlagKeys = \{\n([\s\S]*?)\n\}/.exec(text)![1]!.match(/^ {2}\w+: '[^']*',$/gm)!;
    expect(parseTsServerFlags(text)?.map((f) => `  ${f.identifier}: '${f.key}',`)).toEqual(keys);
  });

  it('unescapes quoted keys', () => {
    const text = OLD.replace("oldThing: 'old-thing'", "oldThing: 'it\\'s'");
    expect(parseTsServerFlags(text)?.at(-1)).toEqual({ key: "it's", identifier: 'oldThing', kind: 'boolean' });
  });

  it('returns undefined for a file without FlagKeys', () => {
    expect(parseTsServerFlags('export const x = 1;\n')).toBeUndefined();
  });

  it('returns undefined when a FlagKeys entry is not recognizable', () => {
    expect(parseTsServerFlags(OLD.replace("maxItems: 'max-items',", 'maxItems: computeKey(),'))).toBeUndefined();
  });

  it('returns undefined when a FlagKeys entry has no method', () => {
    expect(parseTsServerFlags(OLD.replace("oldThing: 'old-thing',", "oldThing: 'old-thing',\n  ghost: 'ghost',"))).toBeUndefined();
  });
});

describe('summarizeFlagChanges', () => {
  it('reports added, removed, renamed and changed-kind flags', () => {
    const next = OLD.replace('fallback: unknown): Promise<unknown> {\n    return this.client.jsonVariation', 'fallback: string): Promise<string> {\n    return this.client.stringVariation')
      .replaceAll('maxItems', 'itemLimit')
      .replace("  oldThing: 'old-thing',\n", "  newThing: 'new-thing',\n")
      .replace('oldThing(context', 'newThing(context')
      .replace("boolVariation('old-thing'", "boolVariation('new-thing'");
    expect(summarizeFlagChanges(OLD, next)).toBe(
      'flags: 1 added (new-thing), 1 removed (old-thing), 1 renamed (max-items: maxItems → itemLimit), 1 changed kind (checkout-config: json → string)',
    );
  });

  it('says so when no flag changed (for example a generator upgrade)', () => {
    expect(summarizeFlagChanges(OLD.replace('0.1.0', '0.0.9'), OLD)).toBe('flags: no changes');
  });

  it('returns undefined when either side cannot be parsed', () => {
    expect(summarizeFlagChanges('garbage', OLD)).toBeUndefined();
    expect(summarizeFlagChanges(OLD, 'garbage')).toBeUndefined();
  });
});
