/**
 * Small line-oriented string builder shared by every emitter
 * (DESIGN.md → Emitters). Emitters write canonical text through it, so
 * indentation, the generated-file header and (later) comment escaping are
 * handled once here.
 */

export interface WriterOptions {
  /** One level of indentation. Default two spaces; Go uses a tab. */
  indent?: string;
  /** Line-comment prefix used by `header`. Default `//`. */
  commentPrefix?: string;
}

export interface HeaderInfo {
  projectKey: string;
  generatorVersion: string;
}

export const GENERATED_MARKER = 'Code generated by launchdarkly-codegen. DO NOT EDIT.';

export class Writer {
  private readonly lines: string[] = [];
  private readonly unit: string;
  private readonly commentPrefix: string;
  private depth = 0;

  constructor(options: WriterOptions = {}) {
    this.unit = options.indent ?? '  ';
    this.commentPrefix = options.commentPrefix ?? '//';
  }

  /** Appends one line at the current indentation. An empty line has no indent. */
  line(text = ''): this {
    this.lines.push(text === '' ? '' : this.unit.repeat(this.depth) + text);
    return this;
  }

  /** Runs `body` one indentation level deeper. */
  indent(body: () => void): this {
    this.depth++;
    try {
      body();
    } finally {
      this.depth--;
    }
    return this;
  }

  /** Writes `open`, the indented `body`, then `close`. */
  block(open: string, close: string, body: () => void): this {
    this.line(open);
    this.indent(body);
    return this.line(close);
  }

  /** The generated-file header every output file starts with. */
  header(info: HeaderInfo): this {
    const p = this.commentPrefix;
    this.line(`${p} ${GENERATED_MARKER}`);
    return this.line(`${p} project: ${info.projectKey}   generator: ${info.generatorVersion}`);
  }

  /** The text written so far, each line terminated by `\n`. */
  toString(): string {
    return this.lines.map((l) => l + '\n').join('');
  }
}
