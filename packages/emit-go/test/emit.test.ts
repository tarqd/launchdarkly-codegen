import { describe, expect, it } from 'vitest';
import type { FlagModel } from '@launchtarqly/core';
import { goEmitter } from '../src/index.js';
import { modelFlag } from '../../core/test/builders.js';

const cfg = { id: 'go', out: 'internal/ldflags/flags_gen.go', sdkMajor: 7, options: { package: 'ldflags' } } as const;
const ctx = { generatorVersion: '0.3.0' };

/** Everything the file holds before the first flag method (DESIGN.md → go sample). */
const PREAMBLE = `// Code generated by launchdarkly-codegen. DO NOT EDIT.
// project: my-project   generator: 0.3.0

// Package ldflags is a type-safe wrapper around the LaunchDarkly Go server SDK
// for the flags in project my-project.
package ldflags

import (
\tgocontext "context"

\t"github.com/launchdarkly/go-sdk-common/v3/ldcontext"
\t"github.com/launchdarkly/go-sdk-common/v3/ldreason"
\t"github.com/launchdarkly/go-sdk-common/v3/ldvalue"
)

// Client is the subset of the LaunchDarkly client that Flags calls: the typed
// evaluation methods for every flag kind. *ld.LDClient satisfies it.
type Client interface {
\tBoolVariation(key string, context ldcontext.Context, defaultVal bool) (bool, error)
\tBoolVariationDetail(key string, context ldcontext.Context, defaultVal bool) (bool, ldreason.EvaluationDetail, error)
\tBoolVariationCtx(ctx gocontext.Context, key string, context ldcontext.Context, defaultVal bool) (bool, error)
\tBoolVariationDetailCtx(ctx gocontext.Context, key string, context ldcontext.Context, defaultVal bool) (bool, ldreason.EvaluationDetail, error)
\tStringVariation(key string, context ldcontext.Context, defaultVal string) (string, error)
\tStringVariationDetail(key string, context ldcontext.Context, defaultVal string) (string, ldreason.EvaluationDetail, error)
\tStringVariationCtx(ctx gocontext.Context, key string, context ldcontext.Context, defaultVal string) (string, error)
\tStringVariationDetailCtx(ctx gocontext.Context, key string, context ldcontext.Context, defaultVal string) (string, ldreason.EvaluationDetail, error)
\tFloat64Variation(key string, context ldcontext.Context, defaultVal float64) (float64, error)
\tFloat64VariationDetail(key string, context ldcontext.Context, defaultVal float64) (float64, ldreason.EvaluationDetail, error)
\tFloat64VariationCtx(ctx gocontext.Context, key string, context ldcontext.Context, defaultVal float64) (float64, error)
\tFloat64VariationDetailCtx(ctx gocontext.Context, key string, context ldcontext.Context, defaultVal float64) (float64, ldreason.EvaluationDetail, error)
\tIntVariation(key string, context ldcontext.Context, defaultVal int) (int, error)
\tIntVariationDetail(key string, context ldcontext.Context, defaultVal int) (int, ldreason.EvaluationDetail, error)
\tIntVariationCtx(ctx gocontext.Context, key string, context ldcontext.Context, defaultVal int) (int, error)
\tIntVariationDetailCtx(ctx gocontext.Context, key string, context ldcontext.Context, defaultVal int) (int, ldreason.EvaluationDetail, error)
\tJSONVariation(key string, context ldcontext.Context, defaultVal ldvalue.Value) (ldvalue.Value, error)
\tJSONVariationDetail(key string, context ldcontext.Context, defaultVal ldvalue.Value) (ldvalue.Value, ldreason.EvaluationDetail, error)
\tJSONVariationCtx(ctx gocontext.Context, key string, context ldcontext.Context, defaultVal ldvalue.Value) (ldvalue.Value, error)
\tJSONVariationDetailCtx(ctx gocontext.Context, key string, context ldcontext.Context, defaultVal ldvalue.Value) (ldvalue.Value, ldreason.EvaluationDetail, error)
}

// Flags evaluates the flags of project my-project.
type Flags struct{ client Client }

// New returns a Flags that evaluates through client.
func New(client Client) *Flags { return &Flags{client: client} }
`;

function emitOne(model: FlagModel): string {
  const files = goEmitter.emit(model, cfg, ctx);
  expect(files.map((f) => f.path)).toEqual(['internal/ldflags/flags_gen.go']);
  return files[0]!.contents;
}

describe('go emitter', () => {
  it('emits the Client interface, Flags, New, four methods per flag and the key constants', () => {
    const model: FlagModel = {
      projectKey: 'my-project',
      flags: [{ ...modelFlag('checkout-v2'), name: 'Checkout V2' }],
    };
    expect(emitOne(model)).toBe(
      PREAMBLE +
        `
// CheckoutV2 evaluates the "Checkout V2" flag.
//
// key: "checkout-v2"
// https://app.launchdarkly.com/projects/my-project/flags/checkout-v2
func (f *Flags) CheckoutV2(context ldcontext.Context, fallback bool) (bool, error) {
\treturn f.client.BoolVariation(KeyCheckoutV2, context, fallback)
}

// CheckoutV2Detail is CheckoutV2 with the evaluation reason.
func (f *Flags) CheckoutV2Detail(context ldcontext.Context, fallback bool) (bool, ldreason.EvaluationDetail, error) {
\treturn f.client.BoolVariationDetail(KeyCheckoutV2, context, fallback)
}

// CheckoutV2Ctx is CheckoutV2 with a Go context for SDK hooks.
func (f *Flags) CheckoutV2Ctx(ctx gocontext.Context, context ldcontext.Context, fallback bool) (bool, error) {
\treturn f.client.BoolVariationCtx(ctx, KeyCheckoutV2, context, fallback)
}

// CheckoutV2DetailCtx is CheckoutV2Detail with a Go context for SDK hooks.
func (f *Flags) CheckoutV2DetailCtx(ctx gocontext.Context, context ldcontext.Context, fallback bool) (bool, ldreason.EvaluationDetail, error) {
\treturn f.client.BoolVariationDetailCtx(ctx, KeyCheckoutV2, context, fallback)
}

// Flag keys, for code that needs the raw key.
const (
\tKeyCheckoutV2 = "checkout-v2"
)
`,
    );
  });

  it('documents the primary method with the description, the trailer and the UI link (DESIGN.md → go sample)', () => {
    const flag = modelFlag('checkout-v2', {
      name: 'Checkout V2',
      description: 'Routes eligible users to the rewritten checkout flow.',
      tags: ['checkout', 'q3'],
      maintainer: { kind: 'member', email: 'ada@example.com', name: 'Ada Lovelace' },
    });
    const out = emitOne({ projectKey: 'my-project', flags: [flag] });
    expect(out).toContain(`
// CheckoutV2 evaluates the "Checkout V2" flag.
//
// Routes eligible users to the rewritten checkout flow.
//
// key: "checkout-v2" · tags: checkout, q3 · maintainer: ada@example.com
// https://app.launchdarkly.com/projects/my-project/flags/checkout-v2
func (f *Flags) CheckoutV2(context ldcontext.Context, fallback bool) (bool, error) {
`);
    expect(out).toContain('\n// CheckoutV2Detail is CheckoutV2 with the evaluation reason.\nfunc ');
  });

  it('shows a team maintainer as team <name>', () => {
    const flag = modelFlag('checkout-v2', { maintainer: { kind: 'team', key: 'payments', name: 'Payments' } });
    expect(emitOne({ projectKey: 'my-project', flags: [flag] })).toContain('\n// key: "checkout-v2" · maintainer: team Payments\n');
  });

  describe('a deprecated flag', () => {
    const model: FlagModel = {
      projectKey: 'my-project',
      flags: [
        modelFlag('checkout-config', {
          name: 'Checkout config',
          kind: 'json',
          deprecated: true,
          deprecationMessage: 'Use checkout-layout instead.',
        }),
        modelFlag('checkout-v2'),
        modelFlag('pricing-tier'),
      ],
    };

    it('gets a Deprecated: paragraph on all four methods', () => {
      const out = emitOne(model);
      expect(out).toContain(`
// key: "checkout-config"
// https://app.launchdarkly.com/projects/my-project/flags/checkout-config
//
// Deprecated: Use checkout-layout instead.
func (f *Flags) CheckoutConfig(context ldcontext.Context, fallback ldvalue.Value) (ldvalue.Value, error) {
`);
      for (const [suffix, doc] of [
        ['Detail', 'is CheckoutConfig with the evaluation reason.'],
        ['Ctx', 'is CheckoutConfig with a Go context for SDK hooks.'],
        ['DetailCtx', 'is CheckoutConfigDetail with a Go context for SDK hooks.'],
      ]) {
        expect(out).toContain(`
// CheckoutConfig${suffix} ${doc}
//
// Deprecated: Use checkout-layout instead.
func (f *Flags) CheckoutConfig${suffix}(`);
      }
      expect(out.match(/Deprecated:/g)).toHaveLength(5);
    });

    it('gets a Deprecated: comment on its constant inside the group, which ends the = alignment run', () => {
      const out = emitOne(model);
      expect(out.slice(out.indexOf('// Flag keys'))).toBe(`// Flag keys, for code that needs the raw key.
const (
\t// Deprecated: Use checkout-layout instead.
\tKeyCheckoutConfig = "checkout-config"
\tKeyCheckoutV2     = "checkout-v2"
\tKeyPricingTier    = "pricing-tier"
)
`);
    });

    it('starts a new alignment run after a deprecated constant mid-group', () => {
      const flags = [modelFlag('a'), modelFlag('bb-long-name'), modelFlag('c', { deprecated: true }), modelFlag('dd')];
      const out = emitOne({ projectKey: 'my-project', flags });
      expect(out.slice(out.indexOf('const ('))).toBe(`const (
\tKeyA          = "a"
\tKeyBbLongName = "bb-long-name"
\t// Deprecated: The "c" flag is deprecated.
\tKeyC  = "c"
\tKeyDd = "dd"
)
`);
    });

    it('without a message says the flag is deprecated, naming it', () => {
      const out = emitOne({ projectKey: 'my-project', flags: [modelFlag('legacy-cart', { deprecated: true })] });
      expect(out).toContain('\n//\n// Deprecated: The "legacy-cart" flag is deprecated.\nfunc (f *Flags) LegacyCart(');
    });
  });

  it('names a flag by its go alias and aligns the key constants as gofmt does', () => {
    const model: FlagModel = {
      projectKey: 'my-project',
      flags: [
        { ...modelFlag('2fa-enabled'), aliases: { go: 'TwoFactorEnabled', 'ts-server': 'twoFactor' } },
        modelFlag('beta.dark_mode'),
      ],
    };
    const out = emitOne(model);
    expect(out).toContain('func (f *Flags) TwoFactorEnabledDetail(context ldcontext.Context');
    expect(out).toContain('\treturn f.client.BoolVariation(KeyBetaDarkMode, context, fallback)\n');
    expect(out.slice(out.indexOf('const ('))).toBe(`const (
\tKeyTwoFactorEnabled = "2fa-enabled"
\tKeyBetaDarkMode     = "beta.dark_mode"
)
`);
  });

  it.each([
    ['string', undefined, 'StringVariation', 'string'],
    ['number', undefined, 'Float64Variation', 'float64'],
    ['number', 'double', 'Float64Variation', 'float64'],
    ['number', 'int', 'IntVariation', 'int'],
    ['json', undefined, 'JSONVariation', 'ldvalue.Value'],
  ] as const)('maps a %s flag (numberType %s) to %s returning %s', (kind, numberType, method, type) => {
    const flag = { ...modelFlag('limit'), kind, ...(numberType ? { numberType } : {}) };
    const out = emitOne({ projectKey: 'my-project', flags: [flag] });
    expect(out).toContain(
      `func (f *Flags) Limit(context ldcontext.Context, fallback ${type}) (${type}, error) {
\treturn f.client.${method}(KeyLimit, context, fallback)
}`,
    );
    expect(out).toContain(
      `func (f *Flags) LimitDetailCtx(ctx gocontext.Context, context ldcontext.Context, fallback ${type}) (${type}, ldreason.EvaluationDetail, error) {
\treturn f.client.${method}DetailCtx(ctx, KeyLimit, context, fallback)
}`,
    );
  });
});
