import { describe, expect, it } from 'vitest';
import type { FlagModel } from '@launchtarqly/core';
import { dotnetEmitter } from '../src/index.js';
import { modelFlag } from '../../core/test/builders.js';

const cfg = { id: 'dotnet', out: 'src/FeatureFlags/Flags.g.cs', sdkMajor: 8, namespace: 'MyApp.FeatureFlags' } as const;
const ctx = { generatorVersion: '0.3.0' };

describe('dotnet emitter', () => {
  it('emits a Flags class and FlagKeys constants for boolean flags', () => {
    const model: FlagModel = {
      projectKey: 'my-project',
      flags: [modelFlag('checkout-v2', { name: 'Checkout V2' }), modelFlag('dark_mode')],
    };
    expect(dotnetEmitter.emit(model, cfg, ctx)).toEqual([
      {
        path: 'src/FeatureFlags/Flags.g.cs',
        contents: `// Code generated by launchdarkly-codegen. DO NOT EDIT.
// project: my-project   generator: 0.3.0
// <auto-generated/>

using LaunchDarkly.Sdk;
using LaunchDarkly.Sdk.Server.Interfaces;

namespace MyApp.FeatureFlags
{
    /// <summary>
    /// Typed accessors for the flags in LaunchDarkly project <c>my-project</c>.
    /// </summary>
    public sealed class Flags
    {
        private readonly ILdClient _client;

        /// <summary>
        /// Creates a wrapper that evaluates flags through <paramref name="client"/>.
        /// </summary>
        /// <param name="client">The LaunchDarkly client, usually an <c>LdClient</c>.</param>
        public Flags(ILdClient client)
        {
            _client = client;
        }

        /// <summary>
        /// Checkout V2
        /// </summary>
        /// <param name="context">The context to evaluate the flag for.</param>
        /// <param name="fallback">The value to use if the flag can't be evaluated.</param>
        /// <returns>The flag's value for <paramref name="context"/>.</returns>
        public bool CheckoutV2(Context context, bool fallback)
        {
            return _client.BoolVariation(FlagKeys.CheckoutV2, context, fallback);
        }

        /// <summary>Checkout V2, with the reason for the value. See <see cref="CheckoutV2"/>.</summary>
        /// <param name="context">The context to evaluate the flag for.</param>
        /// <param name="fallback">The value to use if the flag can't be evaluated.</param>
        /// <returns>The flag's value and the reason it was chosen.</returns>
        public EvaluationDetail<bool> CheckoutV2Detail(Context context, bool fallback)
        {
            return _client.BoolVariationDetail(FlagKeys.CheckoutV2, context, fallback);
        }

        /// <summary>
        /// dark_mode
        /// </summary>
        /// <param name="context">The context to evaluate the flag for.</param>
        /// <param name="fallback">The value to use if the flag can't be evaluated.</param>
        /// <returns>The flag's value for <paramref name="context"/>.</returns>
        public bool DarkMode(Context context, bool fallback)
        {
            return _client.BoolVariation(FlagKeys.DarkMode, context, fallback);
        }

        /// <summary>dark_mode, with the reason for the value. See <see cref="DarkMode"/>.</summary>
        /// <param name="context">The context to evaluate the flag for.</param>
        /// <param name="fallback">The value to use if the flag can't be evaluated.</param>
        /// <returns>The flag's value and the reason it was chosen.</returns>
        public EvaluationDetail<bool> DarkModeDetail(Context context, bool fallback)
        {
            return _client.BoolVariationDetail(FlagKeys.DarkMode, context, fallback);
        }
    }

    /// <summary>
    /// The raw key of every flag in <see cref="Flags"/>.
    /// </summary>
    public static class FlagKeys
    {
        /// <summary>Key of the flag behind <see cref="Flags.CheckoutV2"/>.</summary>
        public const string CheckoutV2 = "checkout-v2";

        /// <summary>Key of the flag behind <see cref="Flags.DarkMode"/>.</summary>
        public const string DarkMode = "dark_mode";
    }
}
`,
      },
    ]);
  });

  it.each([
    ['string', { kind: 'string' }, 'string', 'StringVariation'],
    ['number (double by default)', { kind: 'number', numberType: 'double' }, 'double', 'DoubleVariation'],
    ['number with codegen.number int', { kind: 'number', numberType: 'int' }, 'int', 'IntVariation'],
    ['json', { kind: 'json' }, 'LdValue', 'JsonVariation'],
  ] as const)('maps a %s flag to its typed SDK method', (_name, extra, type, method) => {
    const [file] = dotnetEmitter.emit({ projectKey: 'my-project', flags: [{ ...modelFlag('my-flag'), ...extra }] }, cfg, ctx);
    expect(file?.contents).toContain(`        public ${type} MyFlag(Context context, ${type} fallback)
        {
            return _client.${method}(FlagKeys.MyFlag, context, fallback);
        }
`);
    expect(file?.contents).toContain(`        public EvaluationDetail<${type}> MyFlagDetail(Context context, ${type} fallback)
        {
            return _client.${method}Detail(FlagKeys.MyFlag, context, fallback);
        }
`);
  });
});
